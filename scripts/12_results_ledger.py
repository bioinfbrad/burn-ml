#!/usr/bin/env python3
"""
12_results_ledger.py — every number the manuscript needs, in one place,
read directly from the result files (never transcribed by hand).

Sources:
  --run1     run1/results : the primary of record (run 1) plus every
             random-initialisation arm copied in by s12_run1_reports.sh,
             with its comparison, sensitivity and post hoc reports
  --results  results      : the replicate run (run 2) and the extension
             (repeats, learning curves, Grad-CAM, archival ensemble)

Each section names the file it was read from.

Usage:
    python 12_results_ledger.py --run1 run1/results --results results \
        --out RESULTS_LEDGER.md
"""
import argparse
import csv
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import burnml

TASKS = ("classification", "detection")
PRIMARY = "efficientnetb0"
ARM_LABEL = {
    "efficientnetb0": "EfficientNetB0, ImageNet (primary)",
    "densenet121": "DenseNet121, ImageNet",
    "resnet50v2": "ResNet50V2, ImageNet",
    "mobilenetv2": "MobileNetV2, ImageNet",
    "scratch": "Original CNN (legacy pipeline)",
    "efficientnetb0_randominit": "EfficientNetB0, random init (pre-specified)",
    "efficientnetb0_randominit_steps": "EfficientNetB0, random init, step-matched (pre-specified secondary)",
    "efficientnetb0_randominit_widelr": "EfficientNetB0, random init, grid to 3e-2 (post hoc)",
    "efficientnetb0_randominit_bracket": "EfficientNetB0, random init, grid to 3e-1 (post hoc)",
}


def jl(path):
    return json.load(open(path)) if os.path.exists(path) else None


def ci(x):
    return f"{x[0]:.3f}–{x[1]:.3f}" if x else "—"


def cito(x, nd=2):
    return f"{x[0]:+.{nd}f} to {x[1]:+.{nd}f}" if x else "—"


def dci(r):
    return f"{r['estimate']:+.3f} ({r['ci95'][0]:+.3f} to {r['ci95'][1]:+.3f})"


def oof(path, labels):
    rows = {r["file"]: r for r in csv.DictReader(open(path))}
    files = sorted(rows)
    y = np.array([labels.index(rows[f]["true_label"]) for f in files])
    P = np.array([[float(rows[f][f"p_{c}"]) for c in labels] for f in files])
    return files, y, P


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run1", required=True)
    ap.add_argument("--results", required=True)
    ap.add_argument("--out", default="RESULTS_LEDGER.md")
    args = ap.parse_args()
    R1, R2 = args.run1, args.results
    # Patient groups are derived from hospital accession numbers, which are
    # identifiers: the ledger numbers patients 1..N instead (sorted group order,
    # the same numbering as scripts/13_paper_figures.py).
    _man = os.path.join(R1, "manifest.csv")
    _groups = sorted({r["patient_group"] for r in csv.DictReader(open(_man))}) if os.path.exists(_man) else []
    anon = lambda g: f"patient {_groups.index(g) + 1}" if g in _groups else "patient (unnumbered)"
    L = ["# Results ledger", "",
         "Generated by `scripts/12_results_ledger.py` from the result files. "
         "Every number below is read from the file named in its section; "
         "none is transcribed by hand. 95% CIs are from the patient-level "
         "cluster bootstrap (2,000 draws); Δ CIs are BCa unless stated.", "",
         "**Primary of record: run 1.** Run 2 (identical folds, seeds and recipe) "
         "is a reproducibility replicate.", ""]

    for task in TASKS:
        labels = burnml.TASKS[task][0]
        T = task.capitalize()
        L += [f"## {T}", ""]

        # 1. primary model ----------------------------------------------------
        m = jl(f"{R1}/{task}/{PRIMARY}/metrics.json")
        if m:
            c = m["ci95"]
            L += [f"### {T}: primary model (run 1)", f"Source: `run1/results/{task}/{PRIMARY}/metrics.json`", "",
                  "| Metric | Estimate (95% CI) |", "|---|---|"]
            for k, lab in (("accuracy", "Accuracy"), ("balanced_accuracy", "Balanced accuracy"),
                           ("macro_f1", "Macro F1"), ("macro_auc", "Macro AUC")):
                L.append(f"| {lab} | {m[k]:.3f} ({ci(c.get(k))}) |")
            cal = m.get("calibration", {})
            L.append(f"| Brier score / ECE | {cal.get('brier', float('nan')):.3f} / {cal.get('ece', float('nan')):.3f} |")
            L += ["", "| Class | Sensitivity (95% CI) | Specificity (95% CI) | AUC |", "|---|---|---|---|"]
            for cl in labels:
                p = m["per_class"][cl]
                L.append(f"| {cl.replace('_', ' ')} | {p['sensitivity']:.3f} ({ci(c.get(cl + '.sensitivity'))}) | "
                         f"{p['specificity']:.3f} ({ci(c.get(cl + '.specificity'))}) | {p['auc']:.3f} |")
            L.append("")

        # 2. patient-level -----------------------------------------------------
        s = jl(f"{R1}/{task}/{PRIMARY}/report/sensitivity.json")
        if s:
            L += [f"### {T}: patient-level analyses (run 1)", f"Source: `run1/results/{task}/{PRIMARY}/report/sensitivity.json`", "",
                  "| Class | Crop-level sens. | Patient-weighted mean (median, range) | Without the dominant patient (excluded) |",
                  "|---|---|---|---|"]
            for cl in labels:
                pw = s["patient_weighted"][cl]; lo = s["leave_dominant_patient_out"].get(cl, {})
                L.append(f"| {cl.replace('_', ' ')} | {lo.get('sensitivity_all', float('nan')):.3f} | "
                         f"{pw['mean_sensitivity']:.3f} ({pw['median_sensitivity']:.3f}, {pw['min']:.2f}–{pw['max']:.2f}; {pw['patients']} patients) | "
                         f"{lo.get('sensitivity_without', float('nan')):.3f} ({anon(lo.get('excluded_patient', ''))}, "
                         f"{lo.get('excluded_crops_of_class', '')} crops) |")
            L += ["", "| Class | Calibration slope (95% CI) | Intercept (95% CI) |", "|---|---|---|"]
            for cl in labels:
                r = s["calibration_ci"][cl]
                sl = r.get("slope_ci95")
                L.append(f"| {cl.replace('_', ' ')} | {r['slope']:.2f} ({sl[0]:.2f} to {sl[1]:.2f}) | "
                         f"{r['intercept']:+.2f} ({cito(r.get('intercept_ci95'))}) |")
            L.append("")

        # 3. all models ----------------------------------------------------------
        cmp_ = jl(f"{R1}/{task}/comparison/backbone_comparison.json")
        if cmp_:
            paired = {r["backbone"]: r for r in cmp_["paired_vs_primary"]}
            L += [f"### {T}: all models on identical patient folds (run 1)",
                  f"Source: `run1/results/{task}/comparison/backbone_comparison.json`", "",
                  "| Model | Accuracy (95% CI) | Balanced acc. | Macro AUC (95% CI) | ECE | Holm p vs primary (AUC) |",
                  "|---|---|---|---|---|---|"]
            for row in sorted(cmp_["table"], key=lambda r: -r["macro_auc"]):
                b = row["backbone"]; pr = paired.get(b, {})
                hp = pr.get("holm_p_macro_auc")
                L.append(f"| {ARM_LABEL.get(b, b)} | {row['accuracy']:.3f} ({row['accuracy_lo']:.3f}–{row['accuracy_hi']:.3f}) | "
                         f"{row['balanced_accuracy']:.3f} | {row['macro_auc']:.3f} ({row['macro_auc_lo']:.3f}–{row['macro_auc_hi']:.3f}) | "
                         f"{row['ece']:.3f} | {f'{hp:.3f}' if hp is not None else '—'} |")
            L += ["", f"#### {T}: does ImageNet pretraining help? (pretrained minus random init, same architecture and folds)", "",
                  "| Comparator | Status | Δ macro AUC (BCa 95% CI) | Δ balanced accuracy (BCa 95% CI) |", "|---|---|---|---|"]
            c = cmp_.get("confirmatory")
            if c:
                L.append(f"| Random init, planned grid {{3e-4, 1e-3, 3e-3}} | **pre-specified confirmatory** | "
                         f"{dci(c['d_macro_auc'])} | {dci(c['d_balanced_accuracy'])} |")
            names = {"steps": ("Random init, step-matched (45 epochs)", "pre-specified secondary"),
                     "widelr": ("Random init, grid extended to 3e-2", "post hoc"),
                     "bracket": ("Random init, grid extended to 3e-1", "post hoc")}
            for key in ("steps", "widelr", "bracket"):
                a = next((x for x in cmp_.get("other_random_init_arms", [])
                          if x["arm"].endswith("_" + key)), None)
                if a:
                    L.append(f"| {names[key][0]} | {names[key][1]} | "
                             f"{dci(a['d_macro_auc'])} | {dci(a['d_balanced_accuracy'])} |")
            if cmp_.get("decomposition"):
                L += ["", "Decomposition (macro AUC): " + "; ".join(
                    f"{d['step']} {dci(d['d_macro_auc'])}" for d in cmp_["decomposition"])]
            L.append("")

        # 4. learning-rate selection of the bracketed arm -----------------------
        bdir = f"{R1}/{task}/{PRIMARY}_randominit_bracket/folds"
        if os.path.isdir(bdir):
            chosen, interior = [], 0
            for f in sorted(os.listdir(bdir)):
                d = json.load(open(os.path.join(bdir, f)))
                grid = sorted(float(k) for k in d["lr_selection_inner_ce"])
                ch = float(d["chosen_lr"]); chosen.append(ch)
                interior += grid[0] < ch < grid[-1]
            L += [f"Random-init learning rate chosen per fold (7-rate grid): "
                  + ", ".join(f"{x:g}" for x in chosen)
                  + f"; interior to the grid in {interior} of {len(chosen)} folds. "
                  f"Source: `run1/results/{task}/{PRIMARY}_randominit_bracket/folds/`", ""]
            w = jl(f"{R1}/{task}/{PRIMARY}_randominit_widelr/metrics.json")
            b = jl(f"{R1}/{task}/{PRIMARY}_randominit_bracket/metrics.json")
            if w and b:
                L += [f"Plateau check: macro AUC with the grid to 3e-2 {w['macro_auc']:.3f}, "
                      f"to 3e-1 {b['macro_auc']:.3f}.", ""]

        # 5. repeated CV ----------------------------------------------------------
        rp = jl(f"{R1}/{task}/repeats_summary.json")
        if rp:
            L += [f"### {T}: repeated patient-grouped cross-validation", f"Source: `run1/results/{task}/repeats_summary.json`", "",
                  "| Model | Repeats | Accuracy mean (SD) [range] | Macro AUC mean (SD) [range] |", "|---|---|---|---|"]
            for mdl in (PRIMARY, f"{PRIMARY}_randominit"):
                r = rp["models"].get(mdl)
                if r:
                    a, u = r["accuracy"], r["macro_auc"]
                    L.append(f"| {ARM_LABEL.get(mdl, mdl)} | {len(r['repeats'])} | {a['mean']:.3f} ({a['sd']:.3f}) [{a['min']:.3f}–{a['max']:.3f}] | "
                             f"{u['mean']:.3f} ({u['sd']:.3f}) [{u['min']:.3f}–{u['max']:.3f}] |")
            L += ["", "Pretrained minus random init (planned grid), within each repeat: " + "; ".join(
                f"repeat {p['repeat']}: Δ AUC {dci(p['d_macro_auc'])}" for p in rp["paired"]), ""]

        # 6. replicate run --------------------------------------------------------
        rows = []
        for mdl in (PRIMARY, "densenet121", "resnet50v2", "mobilenetv2", "scratch"):
            a, b = f"{R1}/{task}/{mdl}/oof_predictions.csv", f"{R2}/{task}/{mdl}/oof_predictions.csv"
            if os.path.exists(a) and os.path.exists(b):
                fa, ya, Pa = oof(a, labels); fb, yb, Pb = oof(b, labels)
                if fa == fb:
                    rows.append((mdl, float((Pa.argmax(1) == ya).mean()), float((Pb.argmax(1) == yb).mean()),
                                 float((Pa.argmax(1) == Pb.argmax(1)).mean())))
        if rows:
            L += [f"### {T}: reproducibility (run 1 vs run 2: identical folds, seeds, recipe)",
                  "Source: `run1/results/*/oof_predictions.csv` vs `results/*/oof_predictions.csv`", "",
                  "| Model | Accuracy run 1 | Accuracy run 2 | Identical crop labels |", "|---|---|---|---|"]
            for mdl, a1, a2, ag in rows:
                L.append(f"| {ARM_LABEL.get(mdl, mdl)} | {a1:.3f} | {a2:.3f} | {100*ag:.1f}% |")
            L.append("")

        # 7. learning curve ---------------------------------------------------------
        lc = jl(f"{R2}/{task}/learning_curve_{PRIMARY}.json")
        if lc:
            L += [f"### {T}: learning curve (EfficientNetB0, ImageNet)", f"Source: `results/{task}/learning_curve_{PRIMARY}.json`", "",
                  "| Training patients per fold | Macro AUC mean [range] | Balanced acc. mean | Dominant FT patient in training |",
                  "|---|---|---|---|"]
            for k in sorted(lc["points"], key=int):
                p = lc["points"][k]
                L.append(f"| {k} | {p['macro_auc']['mean']:.3f} [{p['macro_auc']['min']:.3f}–{p['macro_auc']['max']:.3f}] | "
                         f"{p['balanced_accuracy']['mean']:.3f} | {100*p['dominant_patient_in_training']:.0f}% of folds |")
            if lc.get("full"):
                f_ = lc["full"]
                L.append(f"| all (~15; replicate run) | {f_['macro_auc']:.3f} | {f_['balanced_accuracy']:.3f} | 100% of folds |")
            L.append("")

        # 8. post hoc: selective prediction, aggregation, clustered AUC --------------
        ph = jl(f"{R1}/{task}/{PRIMARY}/report/posthoc.json")
        if ph:
            sp = ph["selective_prediction"]
            L += [f"### {T}: selective prediction, aggregation, clustered AUC (run 1)",
                  f"Source: `run1/results/{task}/{PRIMARY}/report/posthoc.json`", "",
                  f"AURC {ph['aurc']:.3f}.", "",
                  "| Coverage | Accuracy (95% CI) | " + " | ".join(f"{c.replace('_', ' ')} sens. crop / patient-wt" for c in labels) + " |",
                  "|---|---|" + "---|" * len(labels)]
            for k in ("100%", "90%", "80%", "70%"):
                r = sp[k]
                L.append(f"| {k} | {r['accuracy']:.3f} ({ci(r['ci95'].get('accuracy'))}) | " + " | ".join(
                    f"{r['sens_' + c]:.3f} / {r['patient_weighted_sens_' + c]:.3f}" for c in labels) + " |")
            ag = ph["aggregation"]
            px = ag["photograph_x_class"]
            L += ["", f"Photograph × class ({px['units']} units): accuracy {px['accuracy']:.3f}, macro AUC {px['macro_auc']:.3f}."]
            for cl, r in ag["patient_any_detected"].items():
                L.append(f"- {cl.replace('_', ' ')}: detected in {r['patients_detected']}/{r['patients_with_class']} patients with it; "
                         f"false alarm in {r['patients_with_false_alarm']}/{r['patients_without_class']} without it.")
            L += ["", "Clustered (Obuchowski) AUC: " + "; ".join(
                f"{cl.replace('_', ' ')} {r['auc']:.3f} ({ci(r['ci95'])})" for cl, r in ph["obuchowski_auc"].items()), ""]

        # 9. Grad-CAM -----------------------------------------------------------------
        for run, lab in ((f"repeats/r1/{PRIMARY}", "pretrained (repeat 1 models)"),
                         (f"{PRIMARY}_randominit", "random init (planned grid)")):
            g = jl(f"{R2}/{task}/{run}/report/gradcam.json")
            if g:
                sc = g["sanity_check"]
                L.append(f"Grad-CAM, {lab}: panel {len(g['panel'])} crops; similarity to the trained-model map after "
                         "cumulative randomisation (Spearman) " + ", ".join(f"{k} {v['spearman']:+.3f}" for k, v in sc.items())
                         + f". Source: `results/{task}/{run}/report/gradcam.json`")
        # 10. archival -------------------------------------------------------------------
        fr = jl(f"{R2}/{task}/{PRIMARY}/final/final_model_record.json")
        if fr:
            L += ["", f"Archival ensemble: {fr['members']} members trained on {fr['training_crops']} crops from "
                  f"{fr['patients']} patients; inference temperature {fr['inference_temperature']:.3f} "
                  f"(median of the {len(fr['cv_temperatures'])} replicate-run CV folds). Source: `results/{task}/{PRIMARY}/final/final_model_record.json`"]
        L += ["", "---", ""]

    open(args.out, "w").write("\n".join(L) + "\n")
    print(f"Wrote {args.out} ({len(L)} lines)")


if __name__ == "__main__":
    main()
